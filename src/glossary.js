export function inferHanjaInContext(word,choices,context){
 const rules=CONTEXT_HANJA[word];
 if(!rules||!Array.isArray(choices)||choices.length<2)return null;
 const hits=rules.map(rule=>({
  ...rule,score:choices.includes(rule.hanja)?rule.cues.filter(cue=>String(context).includes(cue)).length:0
 })).filter(rule=>rule.score>0).sort((a,b)=>b.score-a.score);
 // If multiple interpretations have equally strong evidence, abstain.
 if(!hits.length||(hits[1]&&hits[0].score===hits[1].score))return null;
 return {type:"hanja",gloss:hits[0].hanja,source:"context-rule",alternatives:choices};
}


